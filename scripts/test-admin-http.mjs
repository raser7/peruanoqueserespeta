import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:4330';
let response = await fetch(base + '/api/admin/channels');
assert.equal(response.status, 401);
response = await fetch(base + '/api/admin/session', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://evil.example' }, body: JSON.stringify({ password: 'temporary-password-for-local-tests' }) });
assert.equal(response.status, 403);
response = await fetch(base + '/api/admin/session', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base }, body: JSON.stringify({ password: 'wrong' }) });
assert.equal(response.status, 401);
response = await fetch(base + '/api/admin/session', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base }, body: JSON.stringify({ password: 'temporary-password-for-local-tests' }) });
assert.equal(response.status, 200);
const cookie = response.headers.get('set-cookie');
assert.ok(cookie.includes('HttpOnly'));
assert.ok(cookie.toLowerCase().includes('samesite=strict'));
response = await fetch(base + '/admin', { headers: { Cookie: cookie } });
const admin = await response.text();
assert.ok(admin.includes('Nueva tarjeta'));
assert.equal(response.headers.get('cache-control'), 'no-store');
response = await fetch(base + '/');
const html = await response.text();
assert.equal((html.match(/href="https:\/\/t\.me\/\+/g) || []).length, 5);
assert.ok(!html.includes('temporary-password-for-local-tests'));
response = await fetch(base + '/api/admin/channels', { method: 'POST', headers: { Cookie: cookie, Origin: 'https://evil.example' } });
assert.equal(response.status, 403);
response = await fetch(base + '/api/admin/session', { method: 'DELETE', headers: { Cookie: cookie, Origin: base } });
assert.equal(response.status, 200);
console.log('OK HTTP: acceso bloqueado sin sesión, login, cookie privada, CSRF, panel sin caché, logout y cinco canales locales.');
